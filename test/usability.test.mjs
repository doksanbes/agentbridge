import test from 'node:test';
import assert from 'node:assert/strict';
import { mkdtemp, readFile, writeFile, rm, lstat } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import path from 'node:path';
import { spawnSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';
import { BEGIN, END, mergeInstructions } from '../dist/managed.js';
import { digest } from '../dist/safety.js';
import { renderHandoff } from '../dist/handoff.js';

const cli = fileURLToPath(new URL('../dist/cli.js', import.meta.url));
async function folder(t) {
  const root = await mkdtemp(path.join(tmpdir(), 'AgentBridge usability ü-'));
  t.after(() => rm(root, { recursive: true, force: true }));
  return root;
}
function run(root, args, expected = 0) {
  const result = spawnSync(process.execPath, [cli, ...args, '--project', root], { encoding: 'utf8', windowsHide: true });
  assert.equal(result.status, expected, result.stderr + result.stdout);
  return result.stdout;
}
const get = (root, name) => readFile(path.join(root, name), 'utf8');
const put = (root, name, text) => writeFile(path.join(root, name), text);

test('missing project explains recovery without creating a directory or echoing its path', async t => {
  const parent = await folder(t);
  const missing = path.join(parent, 'missing project ü');
  const result = spawnSync(process.execPath, [cli, 'init', '--project', missing], { encoding: 'utf8', windowsHide: true });
  assert.equal(result.status, 2);
  assert.equal(result.stdout, '');
  assert.match(result.stderr, /Project directory does not exist\. Create it first, or pass --project <existing-directory>\./);
  assert.ok(!result.stderr.includes(missing));
  await assert.rejects(lstat(missing), { code: 'ENOENT' });
});

test('managed section preserves existing user bytes before and after on every update', () => {
  const user = '\ufeff# Team instructions\r\nKeep the API stable.\r\n@existing/team.md\r\n';
  const initial = mergeInstructions(user, '# Shared\n');
  assert.ok(initial.startsWith(user));
  const suffix = '\r\n# Personal notes\r\nUse the test fixtures.\r\n';
  const updated = mergeInstructions(initial + suffix, '# Shared revised\n');
  assert.ok(updated.startsWith(user)); assert.ok(updated.endsWith(suffix));
  assert.equal(updated.split(BEGIN).length, 2);
  assert.ok(!updated.includes('# Shared\n'));
  assert.equal(mergeInstructions(updated, '# Shared revised\n'), updated);
  // Windows editors can add a UTF-8 BOM before a generated file's first marker.
  const bomOnlyPrefix = '\ufeff' + mergeInstructions(undefined, '# Old\n');
  assert.equal(mergeInstructions(bomOnlyPrefix, '# New\n'), '\ufeff' + mergeInstructions(undefined, '# New\n'));
});

test('broken markers, duplicate markers and reserved source markers fail closed', () => {
  for (const previous of [BEGIN + '\nText', END, `${BEGIN}\n${BEGIN}\n${END}`, `${END}\n${BEGIN}`, `prose ${BEGIN}\n${END}`]) {
    assert.throws(() => mergeInstructions(previous, '# Context\n'), /markers/);
  }
  assert.throws(() => mergeInstructions(undefined, BEGIN), /reserved/);
  assert.throws(() => mergeInstructions('x'.repeat(24000), 'y'.repeat(1000)), /24 KiB/);
});

test('only untouched legacy generated files migrate without duplicating old guidance', () => {
  const legacy = '<!-- Generated by AgentBridge 0.1.0 for Codex. -->\n# Old shared context\n';
  const migrated = mergeInstructions(legacy, '# New shared context\n', digest(legacy));
  assert.ok(migrated.startsWith(BEGIN)); assert.ok(!migrated.includes('# Old shared context'));
  assert.throws(() => mergeInstructions(legacy + 'User addition\n', '# New\n', digest(legacy)), /Legacy/);
  // A matching-looking header alone is not proof of ownership.
  assert.ok(mergeInstructions(legacy, '# New\n').startsWith(legacy));
});

test('handoff records direction and keeps multiline notes within their list item', () => {
  const note = renderHandoff({ from: 'codex', to: 'claude', done: ['Parser passes\n3 tests'], next: ['Verify Unicode'], blocked: ['Carrier sandbox unavailable'] },
    { git: 'no-repository', commits: [], changes: [], omitted: 0 });
  assert.ok(note.includes('From: Codex\nTo: Claude Code'));
  assert.ok(note.includes('- Parser passes\n  3 tests'));
  assert.ok(note.includes('## Next steps\n\n- Verify Unicode'));
  assert.ok(note.includes('## Blockers'));
});

test('CLI preview is readable, JSON remains available, and approved updates preserve user rules', async t => {
  const root = await folder(t); run(root, ['init']);
  const user = '# Team instructions\r\nKeep the public API stable.\r\n';
  await put(root, 'CLAUDE.md', user);
  run(root, ['handoff', '--save', '--from', 'codex', '--to', 'claude', '--done', 'Parser tests pass', '--next', 'Add Unicode fixture', '--blocked', 'Carrier sandbox unavailable']);
  const preview = run(root, ['sync', '--dry-run']);
  assert.ok(preview.includes('CLAUDE.md: unmanaged'));
  assert.ok(preview.includes('## Next steps\n\n- Add Unicode fixture'));
  assert.ok(preview.includes('Keep the public API stable.'));
  assert.ok(preview.includes('Dry run: no files changed.'));
  const json = JSON.parse(run(root, ['sync', '--dry-run', '--json']));
  assert.equal(json.files.length, 3);
  run(root, ['sync'], 2);
  assert.equal(await get(root, 'CLAUDE.md'), user);
  run(root, ['sync', '--approve-overwrite', 'CLAUDE.md']);
  assert.ok((await get(root, 'CLAUDE.md')).startsWith(user));
  await put(root, '.agentbridge/context.md', '# Changed project goal\n');
  run(root, ['sync', '--approve-overwrite', 'AGENTS.md,CLAUDE.md,GEMINI.md']);
  assert.ok((await get(root, 'CLAUDE.md')).startsWith(user));
  assert.ok(run(root, ['status']).includes('CLAUDE.md: unchanged'));
});

test('corrupt note can be explicitly repaired without propagating its credential-like text', async t => {
  const root = await folder(t); run(root, ['init']);
  await put(root, '.agentbridge/handoff.md', 'password=FAKE_SENSITIVE_EXAMPLE');
  run(root, ['handoff'], 2);
  run(root, ['handoff', '--save', '--replace-note', '--next', 'Run unit tests']);
  assert.ok(!(await get(root, '.agentbridge/handoff.md')).includes('password='));
});

