test('edits inside managed content are reported as conflicts while surrounding text survives approval', async t => {
  const root = await folder(t); run(root, ['init']); run(root, ['sync']);
  const original = await get(root, 'GEMINI.md');
  await put(root, 'GEMINI.md', '# User rule\r\nKeep tests offline.\r\n' + original.replace('Describe the next outcome', 'LOCAL CHANGE to next outcome') + '# After\r\n');
  const preview = JSON.parse(run(root, ['sync', '--dry-run', '--json']));
  assert.equal(preview.files[2].status, 'conflict');
  run(root, ['sync', '--approve-overwrite', 'GEMINI.md']);
  const revised = await get(root, 'GEMINI.md');
  assert.ok(revised.startsWith('# User rule\r\nKeep tests offline.\r\n'));
  assert.ok(revised.endsWith('# After\r\n'));
  assert.ok(!revised.includes('LOCAL CHANGE'));
});

test('damaged sections block all outputs without writes', async t => {
  const root = await folder(t); run(root, ['init']);
  await put(root, 'CLAUDE.md', BEGIN + '\nDamaged section\n');
  run(root, ['sync', '--approve-overwrite', 'CLAUDE.md'], 2);
  assert.equal(await get(root, 'CLAUDE.md'), BEGIN + '\nDamaged section\n');
  await assert.rejects(get(root, 'AGENTS.md'), { code: 'ENOENT' });
});
