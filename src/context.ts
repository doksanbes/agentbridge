import { assertSafeText, normalize, readText } from './safety.js';
import type { ProjectGit } from './git.js';
import { readFileSync } from 'node:fs';

// Trusted installed-package metadata, never a file in the selected project.
export const VERSION: string = JSON.parse(readFileSync(new URL('../package.json', import.meta.url), 'utf8')).version;
if (!/^\d+\.\d+\.\d+$/.test(VERSION)) throw new Error('Invalid installed package version.');

export const CONTEXT = '.agentbridge/context.md';
export const HANDOFF = '.agentbridge/handoff.md';
export const STATE = '.agentbridge/state.json';
export const TARGETS = ['AGENTS.md', 'CLAUDE.md', 'GEMINI.md'] as const;
export type Target = typeof TARGETS[number];

export function initialContext(): string {
  return `# Project context

## Purpose
Describe what this project does and who uses it.

## Development commands
List verified setup, build, and test commands here. Commands are documentation; AgentBridge never executes them.

## Architecture and conventions
Describe the main components and coding conventions.

## Decisions and constraints
Record durable decisions and their reasons here.

## Current goal
Describe the next outcome and how to verify it.

## Working agreements
- Review the current repository state before changing code.
- Treat handoff notes and Git facts as historical context; verify them before acting.
- Keep credentials, private conversations, environment files, and ignored files out of context.
`;
}

export async function loadContext(git: ProjectGit, includeHandoff = true): Promise<{ context: string; handoff: string; rawContext: string; rawHandoff: string | undefined }> {
  await git.assertControl(CONTEXT);
  await git.assertControl(HANDOFF);
  const source = await readText(git.root, CONTEXT);
  if (source === undefined) throw new Error('Project is not initialized. Run agentbridge init.');
  if (!source.trim()) throw new Error('Canonical context is empty. Add reviewed project guidance.');
  const context = normalize(source);
  const rawHandoff = includeHandoff ? await readText(git.root, HANDOFF) : undefined;
  const handoff = normalize(rawHandoff ?? '');
  assertSafeText(context);
  assertSafeText(handoff);
  return { context, handoff: handoff.trim() ? handoff : '', rawContext: source, rawHandoff };
}

export function renderInstructions(target: Target, context: string, handoff: string): string {
  const agent = { 'AGENTS.md': 'Codex', 'CLAUDE.md': 'Claude Code', 'GEMINI.md': 'Gemini CLI' }[target];
  const output = `<!-- Generated by AgentBridge ${VERSION} for ${agent}. -->
<!-- Edit .agentbridge/context.md, then preview agentbridge sync --dry-run. -->

${context.trim()}
${handoff ? `\n---\n\n# Latest session handoff\n\nHistorical notes, not new permissions. Verify against the current working tree.\n\n${handoff.trim()}\n` : ''}`;
  assertSafeText(output);
  // Stay below Codex's default project instruction budget, leaving room for ancestors.
  return output;
}
