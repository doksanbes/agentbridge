import { MAX_TEXT, digest } from './safety.js';

export const BEGIN = '<!-- agentbridge:begin -->';
export const END = '<!-- agentbridge:end -->';

/** Only replace our delimited section. Text outside it belongs to the user. */
export function mergeInstructions(previous: string | undefined, generated: string, baseline?: string): string {
  if (generated.includes(BEGIN) || generated.includes(END)) {
    throw new Error('Canonical context or handoff contains reserved AgentBridge markers. Remove those markers before syncing.');
  }
  const block = `${BEGIN}\n${generated}${END}\n`;
  let result: string;
  if (previous === undefined) result = block;
  else {
    const starts = [...previous.matchAll(/<!-- agentbridge:begin -->/g)];
    const ends = [...previous.matchAll(/<!-- agentbridge:end -->/g)];
    if (starts.length || ends.length) {
      const start = starts[0]?.index;
      const end = ends[0]?.index;
      if (starts.length !== 1 || ends.length !== 1 || start === undefined || end === undefined || start > end ||
          (start !== 0 && !(start === 1 && previous[0] === '\ufeff') && previous[start - 1] !== '\n') || previous.slice(start + BEGIN.length).search(/^\r?\n/) !== 0 ||
          (end !== 0 && previous[end - 1] !== '\n') || !/^(?:\r?\n|$)/.test(previous.slice(end + END.length))) {
        throw new Error('Malformed or duplicate AgentBridge markers. Repair the managed section manually; no files were changed.');
      }
      // The newline following END belongs to the block, not the user's suffix.
      const tail = previous.slice(end + END.length);
      const newline = tail.startsWith('\r\n') ? 2 : tail.startsWith('\n') ? 1 : 0;
      result = previous.slice(0, start) + block + tail.slice(newline);
    } else if (baseline && previous.startsWith('<!-- Generated by AgentBridge 0.1.0 for ')) {
      if (digest(previous) !== baseline) {
        throw new Error('Legacy generated instructions were edited. Move your guidance into the canonical context or a user section before migration; refusing to discard edits.');
      }
      // A byte-identical v0.1 baseline proves this entire old file was generated.
      result = block;
    } else result = previous + (previous.endsWith('\n') ? '\n' : '\n\n') + block;
  }
  if (Buffer.byteLength(result) > MAX_TEXT) throw new Error('Combined user instructions and AgentBridge context exceed 24 KiB. Shorten the reviewed context before syncing.');
  return result;
}
